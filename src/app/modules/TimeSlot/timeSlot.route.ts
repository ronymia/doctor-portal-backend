router
  .route('/:id')
  .patch(
    auth(ENUM_USER_ROLE.SUPER_ADMIN, ENUM_USER_ROLE.ADMIN),
    validateRequest(TimeSlotValidations.updateTimeSlotZodSchema),
    TimeSlotControllers.updateTimeSlot,
  );

